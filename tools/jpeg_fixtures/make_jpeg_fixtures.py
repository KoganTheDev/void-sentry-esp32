"""Generate the tiny JPEG fixtures for ESP32/test/native/test_jpeg_gray as a C++ header.

Usage: make_jpeg_fixtures.py <out_header>   (needs Pillow)

The images are baseline 4:2:0 JPEGs like the camera produces. Pixel content is a pure function of the constants below,
so a rerun with the same Pillow/libjpeg build gives the same bytes; the header is committed, so CI never needs Pillow.
"""

import io
import sys

from PIL import Image

QVGA = (320, 240)
UNIFORM_GRAY = 128
DARK = 32
BRIGHT = 224


def encode(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=75, subsampling=2, optimize=False, progressive=False)
    return buf.getvalue()


def build() -> dict[str, bytes]:
    uniform = Image.new("RGB", QVGA, (UNIFORM_GRAY,) * 3)
    half = Image.new("RGB", QVGA, (DARK,) * 3)
    half.paste(Image.new("RGB", (QVGA[0] // 2, QVGA[1]), (BRIGHT,) * 3), (QVGA[0] // 2, 0))
    small = Image.new("RGB", (160, 120), (UNIFORM_GRAY,) * 3)
    half_bytes = encode(half)
    return {
        "kUniformJpeg": encode(uniform),
        "kHalfJpeg": half_bytes,
        "kTruncatedJpeg": half_bytes[: len(half_bytes) // 2],
        "kWrongSizeJpeg": encode(small),
    }


def render(fixtures: dict[str, bytes]) -> str:
    out = [
        "// Generated by tools/jpeg_fixtures/make_jpeg_fixtures.py - do not edit by hand.",
        "// clang-format off",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace jpeg_fixtures",
        "{",
    ]
    for name, data in fixtures.items():
        out.append(f"inline constexpr uint8_t {name}[] = {{")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
        out.append("};")
    out.append("} // namespace jpeg_fixtures")
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write(render(build()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
